// Builds app/js2/content.js from the content arrays in app/js/app.js.
// The nightly tasks keep writing app/js/app.js, so App 2.0 reads the same
// sermons, studies, prayers and plans. Run: node tools/app2-content.js
const fs = require("fs");
const path = require("path");
const src = fs.readFileSync(path.join(__dirname, "../app/js/app.js"), "utf8");
const NAMES = ["VERSES", "DECLARATION", "NIGHT_PRAYER", "DREAM_FIRE_PRAYER", "SERMONS", "BIBLE_STUDY", "PRAYER_POINTS", "LIBRARY_BOOKS", "READING_PLANS"];
function grab(name) {
  const m = new RegExp("(?:const|var|let)\\s+" + name + "\\s*=\\s*").exec(src);
  if (!m) throw new Error("missing " + name);
  let i = m.index + m[0].length, depth = 0, str = null, esc = false;
  const start = i;
  for (; i < src.length; i++) {
    const c = src[i];
    if (str) { if (esc) esc = false; else if (c === "\\") esc = true; else if (c === str) str = null; continue; }
    if (c === '"' || c === "'" || c === "`") { str = c; continue; }
    if (c === "/" && src[i + 1] === "/") { i = src.indexOf("\n", i); continue; }
    if (c === "[" || c === "{") depth++;
    if (c === "]" || c === "}") { depth--; if (depth === 0) return src.slice(start, i + 1); }
  }
}
const out = {};
for (const n of NAMES) out[n] = Function('"use strict";return (' + grab(n) + ")")();
const body = "// Generated by tools/app2-content.js from app/js/app.js. Do not edit by hand.\nwindow.WFN_CONTENT = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(__dirname, "../app/js2/content.js"), body);
console.log("content.js", body.length, "bytes;", NAMES.map((n) => n + ":" + (Array.isArray(out[n]) ? out[n].length : "obj")).join(" "));
